import assert from 'node:assert/strict'
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve, sep } from 'node:path'
import { chromium } from 'playwright'
import { startFolderTestServer } from './folder-test-server.mjs'

// Actual Rust files/history/Regex/watcher; only native dialog answers use the test transport.
const root = await mkdtemp(join(tmpdir(), 'ocompare-features-'))
if (!resolve(root).startsWith(resolve(tmpdir()) + sep)) throw new Error('Unsafe fixture directory')
let server, browser
const checks = []
try {
  const left = join(root, 'left'), right = join(root, 'right')
  await Promise.all([mkdir(join(left, 'nested'), { recursive: true }), mkdir(join(right, 'nested'), { recursive: true })])
  const leftFile = join(left, 'nested', 'ไทย.log'), rightFile = join(right, 'nested', 'ไทย.log')
  await writeFile(leftFile, 'ไทย😀 id=123 status=ok\n')
  await writeFile(rightFile, 'ไทย😀 id=45678 status=ok\n')
  server = await startFolderTestServer(root, 1431)
  browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await browser.newPage({ viewport: { width: 1500, height: 950 } })
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto(server.url); await page.waitForFunction(() => Boolean(window.__ocompare))
  const open = async (side, path) => {
    const field = page.locator(`.side-head[data-side=${side}] .path`)
    await field.fill(path); await field.press('Enter')
    await page.waitForFunction(({ side, path }) => window.__ocompare.sides[side].path === path, { side, path })
  }
  const count = async value => page.waitForFunction(value => window.__ocompare.diffCount() === value, value)
  await open('left', leftFile); await open('right', rightFile); await count(1)
  await page.locator('#file-tools [data-cmd=rules]').click()
  const rulesDialog = page.getByRole('dialog', { name: 'Comparison rules' })
  await rulesDialog.getByRole('button', { name: 'Add rule', exact: true }).click()
  await rulesDialog.getByRole('textbox', { name: 'Rule 1 pattern' }).fill('[0-9]+')
  await rulesDialog.getByRole('button', { name: 'Apply', exact: true }).click()
  await count(0)
  assert.equal(await page.evaluate(() => window.__ocompare.textOf('right')), 'ไทย😀 id=45678 status=ok\n')
  await page.evaluate(() => {
    const v = window.__ocompare
    v.editorFor('right').focus()
    v.editorFor('right').executeEdits('test', [{ range: { startLineNumber: 1, startColumn: 24, endLineNumber: 1, endColumn: 26 }, text: 'fail' }])
  })
  await count(1)
  await page.evaluate(() => { const v = window.__ocompare; v.editorFor('left').focus(); v.editorFor('left').setPosition({ lineNumber: 1, column: 1 }); v.copy('left') })
  await count(0)
  assert.equal(await page.evaluate(() => window.__ocompare.textOf('right')), await readFile(leftFile, 'utf8'))
  await page.evaluate(() => { const editor = window.__ocompare.editorFor('right'); editor.focus(); editor.trigger('test', 'undo', null) })
  await count(1)
  await page.locator('.side-head[data-side=right] .save').click()
  await page.waitForFunction(() => !window.__ocompare.isDirty('right'))
  const saved = await readFile(rightFile, 'utf8')
  assert.notEqual(saved, 'ไทย😀 id=45678 status=ok\n')
  const history = await server.call({ action: 'listHistory', path: rightFile })
  assert.equal(history.length, 1); assert.equal(history[0].reason, 'Save')
  checks.push('Files Regex ignores numeric spans without changing editable source; Save creates verified history')

  await page.locator('#file-tools [data-cmd=history]').click()
  const historyDialog = page.getByRole('dialog', { name: 'History', exact: true })
  await historyDialog.getByRole('radio').first().check()
  await page.evaluate(() => { window.testConfirm = true })
  await historyDialog.getByRole('button', { name: 'Restore', exact: true }).click()
  await page.waitForFunction(() => window.__ocompare.textOf('right') === 'ไทย😀 id=45678 status=ok\n')
  assert.equal(await readFile(rightFile, 'utf8'), 'ไทย😀 id=45678 status=ok\n')
  await historyDialog.getByRole('radio').last().check()
  await historyDialog.getByRole('button', { name: 'Compare with current', exact: true }).click()
  await page.waitForFunction(() => window.__ocompare.sides.left.path?.startsWith('history://'))
  assert.equal(await page.evaluate(() => window.__ocompare.editorFor('left').getRawOptions().readOnly), true)
  assert.equal(await page.evaluate(() => window.__ocompare.copy('right')), false)
  assert.equal(await page.getByRole('tab').count(), 2)
  checks.push('History Restore restores original disk bytes and reloads shared model; snapshot comparison is read-only')

  await page.locator('[data-mode=folders]').click()
  await page.locator('[data-root=left]').fill(left); await page.locator('[data-root=right]').fill(right)
  const compare = page.locator('[data-folder-cmd=compare]')
  const complete = () => page.waitForFunction(() => document.querySelector('.folder-progress').textContent === 'Comparison complete')
  await compare.click(); await complete()
  await page.locator('[data-folder-cmd=rules]').click()
  await page.getByRole('button', { name: 'Regex rules…', exact: true }).click()
  const folderRules = page.getByRole('dialog', { name: 'Comparison rules' })
  await folderRules.getByRole('button', { name: 'Add rule', exact: true }).click()
  await folderRules.getByRole('textbox', { name: 'Rule 1 pattern' }).fill('[0-9]+')
  await folderRules.getByRole('button', { name: 'Apply', exact: true }).click()
  await page.locator('[data-folder-cmd=refresh]').click(); await complete()
  assert.equal(await page.locator('[data-path="nested/ไทย.log"] .folder-status').textContent(), '≈')
  checks.push('Folder Rules UI shares Rust Regex semantics and reports byte-different files as Minor')
  await page.locator('[data-path="nested/ไทย.log"]').click()
  assert.equal(await page.locator('[data-folder-cmd=copy]').isEnabled(), true)
  await writeFile(rightFile, 'external change\n')
  await page.waitForFunction(() => document.querySelector('.folder-progress').textContent.includes('press Refresh'))
  assert.equal(await page.locator('[data-folder-cmd=copy]').isDisabled(), true)
  assert.equal(await readFile(rightFile, 'utf8'), 'external change\n')
  await page.locator('[data-folder-cmd=refresh]').click(); await complete()
  assert.equal(await page.locator('[data-folder-cmd=copy]').isEnabled(), true)
  checks.push('Native recursive watcher marks stale and blocks Copy; only manual Refresh restores execution')

  await page.locator('[data-folder-cmd=copy]').click()
  await page.getByRole('button', { name: 'Left → Right', exact: true }).click()
  const preview = page.getByRole('dialog', { name: 'Review copy plan' })
  await preview.waitFor()
  await writeFile(rightFile, 'changed while preview open\n')
  await page.waitForFunction(() => [...document.querySelectorAll('dialog button')].some(b => b.textContent === 'Copy now' && b.disabled))
  await preview.getByRole('button', { name: 'Cancel', exact: true }).click()
  assert.equal(await readFile(rightFile, 'utf8'), 'changed while preview open\n')
  checks.push('Watcher invalidates and disables an open Copy preview without changing destination')

  await page.locator('[data-folder-cmd=refresh]').click(); await complete()
  await page.locator('[data-folder-cmd=copy]').click(); await page.getByRole('button', { name: 'Left → Right', exact: true }).click()
  await page.getByRole('button', { name: 'Copy now', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.folder-progress').textContent.includes('Copy complete'))
  assert.equal(await readFile(rightFile, 'utf8'), await readFile(leftFile, 'utf8'))
  const copiedHistory = await server.call({ action: 'listHistory', path: rightFile })
  assert.ok(copiedHistory.some(entry => entry.reason === 'Copy'))
  checks.push('Confirmed folder overwrite uses same real backup service as Save')

  await page.setViewportSize({ width: 1000, height: 700 })
  await page.locator('[data-mode=files]').click()
  await page.locator('#theme-toggle').click()
  await page.screenshot({ path: 'docs/evidence/features-dark.png' })
  await page.locator('#theme-toggle').click()
  await page.setViewportSize({ width: 1500, height: 950 })
  await page.screenshot({ path: 'docs/evidence/features-light.png' })
  await page.waitForTimeout(400)
  assert.deepEqual(errors, [])
  console.log(`PASS: ${checks.length} integrated feature scenarios`)
  checks.forEach(check => console.log(`  ${check}`))
} finally {
  await browser?.close(); await server?.close(); await rm(root, { recursive: true, force: true })
}
