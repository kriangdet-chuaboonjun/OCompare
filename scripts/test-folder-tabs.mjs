import assert from 'node:assert/strict'
import { mkdtemp, mkdir, writeFile, readFile, access, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve, sep } from 'node:path'
import { chromium } from 'playwright'
import { startFolderTestServer } from './folder-test-server.mjs'

const root = await mkdtemp(join(tmpdir(), 'ocompare-folder-tabs-'))
if (!resolve(root).startsWith(resolve(tmpdir()) + sep)) throw new Error('Unsafe fixture root')
const exists = (path) => access(path).then(() => true, () => false)
const checks = []
let server, browser
try {
  const [al, ar, bl, br] = ['a-left', 'a-right', 'b-left', 'b-right'].map((name) => join(root, name))
  for (const dir of [al, ar]) {
    for (const sub of ['build/obj', 'builder', 'src/generated', 'other/generated', 'ไทย/ผลลัพธ์'])
      await mkdir(join(dir, sub), { recursive: true })
    for (const file of ['build/obj/a.o', 'builder/keep.txt', 'src/generated/g.cs', 'src/real.cs', 'other/generated/g.cs', 'ไทย/ผลลัพธ์/x.txt'])
      await writeFile(join(dir, file), dir === al ? 'left\n' : 'right\n')
  }
  await mkdir(join(al, 'fresh/generated'), { recursive: true })
  await writeFile(join(al, 'fresh/a.txt'), 'a\n')
  await writeFile(join(al, 'fresh/generated/g.txt'), 'g\n')
  for (const dir of [bl, br]) await mkdir(dir, { recursive: true })
  await writeFile(join(bl, 'only.txt'), 'only\n')

  server = await startFolderTestServer(root, 1452)
  browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await browser.newPage({ viewport: { width: 1500, height: 950 } })
  page.setDefaultTimeout(30000)
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto(server.url)
  await page.waitForFunction(() => Boolean(window.__ocompare))
  await page.locator('[data-mode=folders]').click()

  const panel = page.locator('.folder-tab-panel:not([hidden])')
  const tabs = page.locator('#folder-tabs').getByRole('tab')
  const rows = () => panel.locator('.folder-canvas [data-path]')
  const paths = async () => rows().evaluateAll((els) => els.map((el) => el.dataset.path))
  const tool = (cmd) => page.locator(`#folder-tools .folder-toolbar:not([hidden]) [data-folder-cmd=${cmd}]`)
  const progress = () => panel.locator('.folder-progress')
  const done = () => page.waitForFunction(() => document.querySelector('.folder-tab-panel:not([hidden]) .folder-progress').textContent === 'Comparison complete' && !document.querySelector('.folder-tab-panel:not([hidden]) [data-folder-cmd=compare]').disabled)
  const setRoots = async (left, right) => {
    await panel.locator('[data-root=left]').fill(left)
    await panel.locator('[data-root=right]').fill(right)
  }
  const compare = async () => { await panel.locator('[data-folder-cmd=compare]').click(); await done() }
  const rightClick = async (path) => { await panel.locator(`[data-path="${path}"] .folder-name`).first().click({ button: 'right' }); await page.getByRole('menu').waitFor() }
  const menuNames = () => page.getByRole('menuitem').evaluateAll((els) => els.map((el) => `${el.textContent}${el.getAttribute('aria-disabled') === 'true' ? ' (disabled)' : ''}`))

  // ----- tabs: state is separate per tab -----
  assert.equal(await tabs.count(), 1)
  assert.equal(await tabs.first().textContent(), 'New folders')
  await setRoots(al, ar)
  assert.equal(await tabs.first().textContent(), 'a-left ↔ a-right')
  await compare()
  const firstRows = await paths()
  assert(firstRows.includes('build') && firstRows.includes('src/real.cs'))
  await page.locator('#folder-tab-add').click()
  assert.equal(await tabs.count(), 2)
  assert.equal(await panel.locator('[data-root=left]').inputValue(), '')
  assert.equal((await paths()).length, 0)
  assert((await panel.locator('.folder-summary').textContent()).includes('No comparison yet'))
  await setRoots(bl, br)
  await compare()
  assert.deepEqual(await paths(), ['only.txt'])
  assert.equal(await tabs.nth(1).textContent(), 'b-left ↔ b-right')
  await tabs.first().click()
  assert.deepEqual(await paths(), firstRows)
  await panel.locator('[data-path="build"] .folder-name').first().click()
  await panel.locator('[data-path="src/real.cs"] .folder-name').first().click({ modifiers: ['Control'] })
  await panel.locator('[data-include]').fill('*.cs')
  await panel.locator('[data-include]').press('Enter')
  await panel.locator('[data-include]').blur()
  const filtered = await paths()
  await tabs.nth(1).click()
  assert.equal(await panel.locator('[data-include]').inputValue(), '*.*')
  assert.deepEqual(await paths(), ['only.txt'])
  await tabs.first().click()
  assert.equal(await panel.locator('[data-include]').inputValue(), '*.cs')
  assert.deepEqual(await paths(), filtered)
  assert((await panel.locator('[data-selection]').textContent()).includes('selected'))
  await panel.locator('[data-include]').fill('*.*')
  await panel.locator('[data-include]').press('Enter')
  await panel.locator('[data-include]').blur()
  checks.push('Folder tabs keep separate pairs, results, filters and selection; titles follow the chosen folders')

  // ----- keyboard shortcuts -----
  await page.locator('body').click({ position: { x: 5, y: 5 } })
  await page.keyboard.press('Control+t')
  assert.equal(await tabs.count(), 3)
  assert.equal(await tabs.nth(2).getAttribute('aria-selected'), 'true')
  await page.keyboard.press('Control+Tab')
  assert.equal(await tabs.first().getAttribute('aria-selected'), 'true')
  await page.keyboard.press('Control+Shift+Tab')
  assert.equal(await tabs.nth(2).getAttribute('aria-selected'), 'true')
  await page.keyboard.press('Control+w')
  assert.equal(await tabs.count(), 2)
  await tabs.first().click()
  checks.push('Ctrl+T, Ctrl+W, Ctrl+Tab and Ctrl+Shift+Tab operate on Folder tabs')

  // ----- context menu -----
  await rightClick('build')
  assert.equal((await panel.locator('[data-selection]').textContent()).includes('1 selected'), true, 'right-click selects the unselected row')
  const names = await menuNames()
  for (const wanted of ['Open files (disabled)', 'Ignore folder', 'Manage ignored folders…', 'Select…', 'Expand', 'Collapse', 'Refresh'])
    assert(names.includes(wanted), `${wanted} in ${names}`)
  const box = await page.getByRole('menu').boundingBox()
  assert(box.width >= 200)
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('menu').count(), 0)
  await rightClick('build')
  await page.locator('#logo').click()
  assert.equal(await page.getByRole('menu').count(), 0, 'outside click closes the menu')
  // Blank area: only commands that do not need a selection.
  const scroll = await panel.locator('.folder-scroll').boundingBox()
  await page.mouse.click(scroll.x + 80, scroll.y + scroll.height - 12, { button: 'right' })
  await page.getByRole('menu').waitFor()
  assert.deepEqual(await menuNames(), ['Select all', 'Expand all', 'Collapse all', 'Manage ignored folders…', 'Refresh'])
  await page.keyboard.press('Escape')
  // Keyboard: Shift+F10, arrows, Enter.
  await panel.locator('.folder-scroll').focus()
  await panel.locator('[data-path="builder"] .folder-name').first().click()
  await page.keyboard.press('Shift+F10')
  await page.getByRole('menu').waitFor()
  await page.keyboard.press('ArrowDown')
  assert(await page.evaluate(() => document.activeElement?.classList.contains('context-item')), 'ArrowDown focuses an item')
  await page.keyboard.press('Escape')
  assert.equal(await page.evaluate(() => document.activeElement?.classList.contains('folder-scroll')), true, 'Escape returns focus to the grid')
  checks.push('Menu opens at the pointer, selects the clicked row, shows selection-free commands on blank space, closes on Escape and outside click, and works with Shift+F10')

  // ----- Ignore folder -----
  await rightClick('build')
  await page.getByRole('menuitem', { name: 'Ignore folder', exact: true }).click()
  await done()
  let current = await paths()
  assert(!current.some((p) => p === 'build' || p.startsWith('build/')))
  assert(current.includes('builder'), 'build and builder are different folders')
  assert((await panel.locator('.folder-summary').textContent()).includes('Identical'))
  // Multi-select two folders at different depths; right-click on a selected row keeps both.
  await panel.locator('[data-path="src/generated"] .folder-name').first().click()
  await panel.locator('[data-path="ไทย/ผลลัพธ์"] .folder-name').first().click({ modifiers: ['Control'] })
  assert((await panel.locator('[data-selection]').textContent()).includes('2 selected'))
  await rightClick('src/generated')
  assert((await panel.locator('[data-selection]').textContent()).includes('2 selected'), 'right-click on a selected row keeps the selection')
  await page.getByRole('menuitem', { name: 'Ignore folder', exact: true }).click()
  await done()
  current = await paths()
  assert(!current.some((p) => p.startsWith('src/generated') || p.startsWith('ไทย/ผลลัพธ์')))
  assert(current.includes('other/generated'), 'same name in another location stays')
  assert(current.includes('src/real.cs'))
  // Manage: remove one, clear the rest.
  await rightClick('src')
  await page.getByRole('menuitem', { name: 'Manage ignored folders…' }).click()
  let dialog = page.getByRole('dialog', { name: 'Comparison rules' })
  assert.deepEqual(await dialog.getByRole('list', { name: 'Ignored folders' }).locator('li span').allTextContents(), ['build', 'src/generated', 'ไทย/ผลลัพธ์'])
  await dialog.getByRole('button', { name: 'Remove ignored folder build' }).click()
  await dialog.getByRole('button', { name: 'Apply', exact: true }).click()
  await done()
  assert((await paths()).includes('build/obj/a.o'))
  assert(!(await paths()).includes('src/generated'))
  await rightClick('src')
  await page.getByRole('menuitem', { name: 'Manage ignored folders…' }).click()
  dialog = page.getByRole('dialog', { name: 'Comparison rules' })
  await dialog.getByRole('button', { name: 'Clear all', exact: true }).click()
  await dialog.getByRole('button', { name: 'Apply', exact: true }).click()
  await done()
  assert.equal((await paths()).filter((p) => p.startsWith('src/generated') || p.startsWith('ไทย/ผลลัพธ์')).length, 4)
  checks.push('Ignore folder (single, multiple, similarly named, Thai) recompares automatically; Rules lists, removes and clears ignores')

  // ----- ignores are per tab -----
  await rightClick('build')
  await page.getByRole('menuitem', { name: 'Ignore folder', exact: true }).click()
  await done()
  await tabs.nth(1).click()
  await tool('rules').click()
  assert.equal(await page.getByRole('dialog', { name: 'Comparison rules' }).getByRole('listitem').allTextContents().then((t) => t.join('|')), 'None. Right-click a folder and choose Ignore folder.')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await tabs.first().click()

  // ----- copying a parent folder never includes the ignored subtree -----
  await rightClick('fresh/generated')
  await page.getByRole('menuitem', { name: 'Ignore folder', exact: true }).click()
  await done()
  await panel.locator('[data-path="fresh"] .folder-name').first().click()
  await tool('copy').click()
  await page.getByRole('button', { name: 'Left → Right', exact: true }).click()
  await page.getByRole('dialog', { name: 'Review copy plan' }).waitFor()
  const preview = await page.locator('.copy-preview').textContent()
  assert(preview.includes('fresh/a.txt') && !preview.includes('generated'), preview)
  await page.getByRole('button', { name: 'Copy now', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.folder-tab-panel:not([hidden]) .folder-progress').textContent.includes('Copy complete'))
  assert.equal(await readFile(join(ar, 'fresh/a.txt'), 'utf8'), 'a\n')
  assert.equal(await exists(join(ar, 'fresh/generated')), false)
  checks.push('Copying a parent folder skips ignored descendants; ignores are per tab')

  // ----- menu commands are disabled while scanning -----
  await done().catch(() => {})
  await page.evaluate(() => { window.compareDelayMs = 900 })
  await tool('refresh').click()
  await rightClick('builder')
  assert((await menuNames()).includes('Ignore folder (disabled)'))
  await page.keyboard.press('Escape')
  await done()
  await page.evaluate(() => { window.compareDelayMs = 0 })
  // Menu near the window edge stays inside it.
  await page.setViewportSize({ width: 760, height: 520 })
  await page.waitForFunction(() => innerWidth === 760 && innerHeight === 520)
  await page.waitForTimeout(200)
  const grid = await panel.locator('.folder-scroll').boundingBox()
  await page.mouse.click(grid.x + grid.width - 6, grid.y + grid.height - 6, { button: 'right' })
  await page.getByRole('menu').waitFor()
  const edge = await page.getByRole('menu').boundingBox()
  assert(edge.x >= 0 && edge.y >= 0 && edge.x + edge.width <= 760 && edge.y + edge.height <= 520, JSON.stringify(edge))
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 1500, height: 950 })
  checks.push('Ignore is disabled during a scan; the menu is repositioned inside the window')

  // ----- background jobs: each tab has its own job -----
  await page.evaluate(() => { window.compareDelayMs = 1200 })
  await tool('refresh').click()
  await tabs.nth(1).click()
  await panel.locator('[data-folder-cmd=compare]').click()
  await page.waitForTimeout(100)
  await page.waitForFunction(() => [...document.querySelectorAll('.folder-tab-panel')].every((p) => p.querySelector('.folder-progress').textContent === 'Comparison complete'))
  assert.equal(await page.locator('.folder-summary').first().textContent().then((t) => t.includes('files')), true)
  // Close a scanning tab; the other tab's result is unaffected.
  await tool('refresh').click()
  await tabs.first().click()
  await tool('refresh').click()
  await tabs.nth(1).click()
  await page.keyboard.press('Control+w')
  assert.equal(await tabs.count(), 1)
  await page.waitForFunction(() => document.querySelector('.folder-tab-panel:not([hidden]) .folder-progress').textContent === 'Comparison complete')
  await page.evaluate(() => { window.compareDelayMs = 0 })
  assert((await paths()).includes('fresh'))
  checks.push('Two tabs compare independently; closing one scanning tab leaves the other result intact')

  // ----- watch is per tab -----
  await page.locator('#folder-tab-add').click()
  await setRoots(bl, br)
  await compare()
  await tabs.first().click()
  await writeFile(join(ar, 'watched-change.txt'), 'changed ' + Date.now())
  await page.waitForFunction(() => document.querySelector('.folder-tab-panel:not([hidden]) .folder-progress').textContent.includes('press Refresh'))
  await tabs.nth(1).click()
  assert.equal(await progress().textContent(), 'Comparison complete', 'watching a different pair does not mark this tab stale')
  checks.push('Watching is per tab: a change in one tab\'s folders marks only that tab for refresh')

  // ----- copy is app-wide exclusive -----
  await page.evaluate(() => { window.compareDelayMs = 1500 })
  await tool('refresh').click()
  await tabs.first().click()
  await tool('refresh').click().catch(() => {})
  await page.evaluate(() => { window.compareDelayMs = 0 })
  await page.waitForFunction(() => [...document.querySelectorAll('.folder-tab-panel')].every((p) => p.querySelector('.folder-progress').textContent === 'Comparison complete'))
  await panel.locator('[data-path="src/real.cs"] .folder-name').first().click()
  await tabs.nth(1).click()
  await page.evaluate(() => { window.compareDelayMs = 2000 })
  await tool('refresh').click()
  await tabs.first().click()
  await tool('copy').click()
  await page.getByRole('button', { name: 'Left → Right', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.folder-tab-panel:not([hidden]) .folder-progress').textContent.includes('Another folder job is running'))
  await page.evaluate(() => { window.compareDelayMs = 0 })
  await page.waitForFunction(() => [...document.querySelectorAll('.folder-tab-panel')].every((p) => p.querySelector('.folder-progress').textContent !== 'Scanning…' && !p.querySelector('.folder-progress').textContent.startsWith('Scanning')))
  // Hold a real copy: other tabs stay viewable but cannot compare, and the copying tab cannot close.
  let release
  const gate = new Promise((resolve) => { release = resolve })
  await page.route('**/__folder_test/workspace', async (route) => {
    if (route.request().postDataJSON().action === 'executeCopy') await gate
    await route.continue()
  })
  await panel.locator('[data-path="src/real.cs"] .folder-name').first().click()
  await tool('copy').click()
  await page.getByRole('button', { name: 'Left → Right', exact: true }).click()
  await page.getByRole('button', { name: 'Copy now', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('#folder-tools .folder-toolbar:not([hidden]) [data-folder-cmd=cancel]:not([disabled])'))
  await tabs.nth(1).click()
  await panel.locator('[data-folder-cmd=compare]').click()
  assert((await progress().textContent()).includes('A copy is running'))
  await tabs.first().click()
  await page.keyboard.press('Control+w')
  assert.equal(await tabs.count(), 2, 'a tab that is copying cannot be closed')
  assert((await page.locator('#st-msg').textContent()).includes('Stop the copy'))
  release()
  await page.waitForFunction(() => document.querySelector('.folder-tab-panel:not([hidden]) .folder-progress').textContent.includes('Copy complete'))
  await page.unroute('**/__folder_test/workspace')
  checks.push('Only one copy runs app-wide: other tabs stay viewable but cannot start jobs, and a copying tab cannot close')

  // ----- closing the last tab leaves one empty tab -----
  await page.keyboard.press('Control+w')
  await page.keyboard.press('Control+w')
  assert.equal(await tabs.count(), 1)
  assert.equal(await tabs.first().textContent(), 'New folders')
  assert.equal(await panel.locator('[data-root=left]').inputValue(), '')
  assert.deepEqual(errors, [])
  console.log(`PASS: ${checks.length} Folder tab, Ignore folder and context menu scenarios; real Rust services; no page errors`)
  for (const check of checks) console.log('  ' + check)
} catch (error) {
  const page = browser?.contexts()[0]?.pages()[0]
  if (page) {
    console.error(await page.evaluate(() => ({ progress: document.querySelector('.folder-tab-panel:not([hidden]) .folder-progress')?.textContent, tabs: [...document.querySelectorAll('#folder-tabs [role=tab]')].map((t) => t.textContent), menu: document.querySelector('.context-menu')?.textContent, dialogs: [...document.querySelectorAll('dialog')].map((d) => d.textContent) })))
    await page.screenshot({ path: join(tmpdir(), 'folder-tabs-failure.png') })
  }
  throw error
} finally {
  await browser?.close()
  await server?.close()
  await rm(root, { recursive: true, force: true })
}
